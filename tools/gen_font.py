#!/usr/bin/env python3
"""Generate PBL-7's landscape bitmap font as a C header.

The watch is held sideways, so system fonts (which only draw upright) are
useless. We store each glyph as an upright 1-bit bitmap and blit it pixel by
pixel through the ls()/lp() landscape helper in main.c — the helper performs
the 90-degree rotation at draw time, so the stored glyphs stay human-readable
(no pre-rotation needed here).

Two sizes: SMALL (HUD / body text) and BIG (titles / boss names). Charset is
ASCII 32..126 plus the accented letters the five languages need
(é ü ä ö ß ñ ¡ ¿), in that fixed order after ASCII.

Output:
  src/c/font_data.h         packed glyph rows (uint32_t per row) + widths
  tools/font_preview.png    legibility check (upright)

Run with a Python that has Pillow, e.g.:
  ~/.local/share/uv/tools/pebble-tool/bin/python tools/gen_font.py
"""
import os
from PIL import Image, ImageDraw, ImageFont

FONT_PATH = "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"

# Full Latin-1 accent set for EN/NL/FR/DE/ES (lower + upper) plus ¡ ¿.
SPECIALS = ("àáâäçèéêëíîïñóôöùúûüß"
            "ÀÁÂÄÇÈÉÊËÍÎÏÑÓÔÖÙÚÛÜ"
            "¡¿")
CHARSET = [chr(c) for c in range(32, 127)] + list(SPECIALS)

SIZES = {"S": 11, "B": 23}   # pixel sizes; cropped height comes out smaller
THRESHOLD = 100


def build(px):
    font = ImageFont.truetype(FONT_PATH, px)
    ascent, descent = font.getmetrics()
    H = ascent + descent
    Wmax = px * 2 + 4

    rendered = []
    for ch in CHARSET:
        img = Image.new("L", (Wmax, H), 0)
        d = ImageDraw.Draw(img)
        d.text((1, 0), ch, fill=255, font=font)
        bw = img.point(lambda v: 255 if v >= THRESHOLD else 0)
        rendered.append((ch, bw, bw.getbbox()))

    tops = [b[1] for _, _, b in rendered if b]
    bots = [b[3] for _, _, b in rendered if b]
    top, bot = min(tops), max(bots)
    Hc = bot - top

    glyphs = []
    for ch, bw, bbox in rendered:
        if bbox:
            w = bbox[2] + 1          # advance = right ink edge + 1px bearing
        else:
            w = max(2, px // 3)      # space and other blanks
        rows = []
        for r in range(top, bot):
            val = 0
            for c in range(0, min(w, Wmax)):
                if bw.getpixel((c, r)) >= THRESHOLD:
                    val |= (1 << c)
            rows.append(val)
        glyphs.append((w, rows))
    return Hc, glyphs


def emit_c(f, tag, Hc, glyphs):
    n = len(glyphs)
    f.write("#define FONT_%s_H %d\n" % (tag, Hc))
    f.write("#define FONT_%s_N %d\n" % (tag, n))
    f.write("static const uint8_t FONT_%s_W[%d] = {" % (tag, n))
    f.write(",".join(str(w) for w, _ in glyphs))
    f.write("};\n")
    f.write("static const uint32_t FONT_%s_ROWS[%d][%d] = {\n" % (tag, n, Hc))
    for w, rows in glyphs:
        f.write("  {" + ",".join("0x%X" % r for r in rows) + "},\n")
    f.write("};\n\n")


def preview(sizes):
    scale = 3
    pad = 6
    y = pad
    lines = []
    for tag, (Hc, glyphs) in sizes.items():
        # sample string
        sample = "PBL-7 Aä 0123 é¿"
        lines.append((tag, Hc, glyphs, sample))
    W = 520
    Htot = 0
    for tag, Hc, glyphs, sample in lines:
        Htot += Hc * scale + pad + 14
    img = Image.new("RGB", (W, Htot + pad), (10, 10, 40))
    d = ImageDraw.Draw(img)
    slot = {c: i for i, c in enumerate(CHARSET)}
    for tag, Hc, glyphs, sample in lines:
        x = pad
        for ch in sample:
            i = slot.get(ch, slot["?"])
            w, rows = glyphs[i]
            for r in range(Hc):
                for c in range(w):
                    if (rows[r] >> c) & 1:
                        d.rectangle([x + c * scale, y + r * scale,
                                     x + c * scale + scale - 1, y + r * scale + scale - 1],
                                    fill=(255, 255, 255))
            x += (w + 1) * scale
        y += Hc * scale + pad + 14
    img.save("tools/font_preview.png")


def main():
    built = {}
    for tag, px in SIZES.items():
        built[tag] = build(px)

    with open("src/c/font_data.h", "w") as f:
        f.write("// Auto-generated by tools/gen_font.py — do not edit by hand.\n")
        f.write("#pragma once\n#include <stdint.h>\n\n")
        f.write("// Glyph slots: 0..94 = ASCII 32..126, then 95.. = specials.\n")
        f.write("#define FONT_SPECIAL_N %d\n" % len(SPECIALS))
        f.write("static const uint16_t FONT_SPECIAL_CP[%d] = {" % len(SPECIALS))
        f.write(",".join("0x%X" % ord(c) for c in SPECIALS))
        f.write("};\n\n")
        emit_c(f, "S", *built["S"])
        emit_c(f, "B", *built["B"])
    print("wrote src/c/font_data.h  (S H=%d, B H=%d, %d glyphs)"
          % (built["S"][0], built["B"][0], len(CHARSET)))

    preview(built)
    print("wrote tools/font_preview.png")


if __name__ == "__main__":
    main()
